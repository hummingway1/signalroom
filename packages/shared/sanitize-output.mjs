// §16 — 사용자에게 표시되는 최종 분석/대화 텍스트에서 허용되지 않은 기호를 제거한다.
// 허용: 한글, 영문, 숫자, 공백, 마침표(.), 콤마(,), 물음표(?)
// 내부 JSON/API schema/개발자 로그는 대상이 아니다 — 이 함수는 사용자 출력 직전에만 호출한다.
//
// 실측으로 여러 차례 발견된 버그 수정: 허용되지 않은 기호를 그냥 삭제하면, 그 기호가 실제로는
// 단어/문장 사이를 구분하는 역할을 하고 있었을 경우 옆 단어와 붙어버린다
// (예: "시작해보자!선택권을" → "시작해보자선택권을", "Deci·Ryan" → "DeciRyan",
//  "코치야~진단이나" → "코치야진단이나"). 문장을 끝맺는 의미가 강한 기호(!;~…—)는 마침표로
// 치환하고, 그 외 나머지 비허용 기호(가운뎃점·콜론·괄호·이모지 등)는 완전히 삭제하는 대신
// 공백으로 치환해서 — 어떤 기호가 오더라도 최소한 단어가 서로 붙는 일은 없게 한다.
export function sanitizeUserFacingText(text) {
  if (typeof text !== 'string') return text;
  return text
    .replace(/[!;~…—]/g, '.') // 문장 경계 역할을 하는 기호는 마침표로 치환(문장 붙음 방지)
    .replace(/[^가-힣ㄱ-ㅎㅏ-ㅣa-zA-Z0-9\s.,?]/g, ' ') // 나머지 비허용 기호는 삭제 대신 공백으로(단어 붙음 방지)
    .replace(/\.{2,}/g, '.') // 위 치환으로 마침표가 연달아 생기는 경우 정리
    .replace(/([.,?])(?=[가-힣a-zA-Z])/g, '$1 ') // 문장부호 뒤 글자가 공백 없이 붙으면 한 칸 띄운다(가독성). 숫자 뒤는 제외해서 소수점(3.5)/천단위 구분(1,000)을 보호한다.
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
